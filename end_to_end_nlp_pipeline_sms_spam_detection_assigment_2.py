def predict_message(message):
    cleaned = clean_text(message)
    features = tfidf.transform([cleaned])
    prediction = int(model.predict(features)[0])
    spam_probability = float(model.predict_proba(features)[0, 1])

    label = "spam" if prediction == 1 else "ham (not spam)"
    return {
        "message": message,
        "prediction": label,
        "spam_probability": round(spam_probability, 3)
    }

examples = [
    "Congratulations! You have won a free prize. Call now!",
    "Hey, are we still meeting at 6 pm?",
    "URGENT! Claim your cash reward by clicking this link."
]

for message in examples:
    print(predict_message(message))

from sklearn.pipeline import Pipeline
import joblib

deployment_pipeline = Pipeline([
    ("tfidf", TfidfVectorizer(
        ngram_range=(1, 2),
        min_df=2,
        max_features=20000,
        sublinear_tf=True
    )),
    ("classifier", LogisticRegression(max_iter=1000, random_state=42))
])

deployment_pipeline.fit(X_train_text, y_train)

MODEL_PATH = "sms_spam_pipeline.joblib"
joblib.dump(deployment_pipeline, MODEL_PATH)
print("Saved model to:", MODEL_PATH)

loaded_pipeline = joblib.load("sms_spam_pipeline.joblib")

def deployed_predict(message):
    # Apply the same basic cleaning used in training.
    cleaned = clean_text(message)
    prediction = int(loaded_pipeline.predict([cleaned])[0])
    probability = float(loaded_pipeline.predict_proba([cleaned])[0, 1])
    return {
        "label": "spam" if prediction == 1 else "ham",
        "spam_probability": round(probability, 3)
    }

