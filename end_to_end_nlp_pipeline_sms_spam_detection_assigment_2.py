from fastapi import FastAPI
from pydantic import BaseModel, Field

app = FastAPI(title="SMS Spam Classifier")
pipeline = joblib.load("sms_spam_pipeline.joblib")

class MessageRequest(BaseModel):
    text: str = Field(min_length=1, max_length=5000)

def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"https?://\S+|www\.\S+", " URL ", text)
    text = re.sub(r"\b[\w.-]+@[\w.-]+\.\w+\b", " EMAIL ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text

@app.get("/health")
def health():
    return {"status": "ok"}

@app.post("/predict")
def predict(request: MessageRequest):
    cleaned = clean_text(request.text)
    prediction = int(pipeline.predict([cleaned])[0])
    probability = float(pipeline.predict_proba([cleaned])[0, 1])
    return {
        "label": "spam" if prediction == 1 else "ham",
        "spam_probability": round(probability, 3)
    }

