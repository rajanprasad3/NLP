import io
import re
import zipfile
import urllib.request
from pathlib import Path

import pandas as pd
import numpy as np

DATA_URL = "https://archive.ics.uci.edu/static/public/228/sms+spam+collection.zip"

with urllib.request.urlopen(DATA_URL) as response:
    zip_bytes = response.read()

with zipfile.ZipFile(io.BytesIO(zip_bytes)) as z:
    # The archive contains a file named SMSSpamCollection.
    data_file = next(name for name in z.namelist() if name.endswith("SMSSpamCollection"))
    with z.open(data_file) as f:
        df = pd.read_csv(
            f,
            sep="\t",
            header=None,
            names=["label", "text"],
            encoding="utf-8"
        )

print("Dataset shape:", df.shape)
df.head()

print("Rows and columns:", df.shape)
print("\nMissing values:")
print(df.isna().sum())

print("\nLabel counts:")
print(df["label"].value_counts())

print("\nLabel proportions:")
print(df["label"].value_counts(normalize=True).round(3))

print("\nExact duplicate rows:", df.duplicated().sum())

# Text Preprocessing

df = df.dropna(subset=["label", "text"]).copy()
df = df.drop_duplicates().reset_index(drop=True)

def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"https?://\S+|www\.\S+", " URL ", text)
    text = re.sub(r"\b[\w.-]+@[\w.-]+\.\w+\b", " EMAIL ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text

df["clean_text"] = df["text"].apply(clean_text)

df[["label", "text", "clean_text"]].head(10)

# Label preparation
label_map = {"ham": 0, "spam": 1}
df["target"] = df["label"].map(label_map)

if df["target"].isna().any():
    raise ValueError("Unexpected label found. Inspect df['label'].unique().")

print(df[["label", "target", "clean_text"]].head())
print("\nNumeric target counts:")
print(df["target"].value_counts())

# Feature Engineering

from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer

X_train_text, X_test_text, y_train, y_test = train_test_split(
    df["clean_text"],
    df["target"],
    test_size=0.20,
    random_state=42,
    stratify=df["target"]
)

tfidf = TfidfVectorizer(
    ngram_range=(1, 2),
    min_df=2,
    max_features=20000,
    sublinear_tf=True
)

X_train = tfidf.fit_transform(X_train_text)
X_test = tfidf.transform(X_test_text)

print("Training feature matrix:", X_train.shape)
print("Test feature matrix:", X_test.shape)
print("Example learned features:", tfidf.get_feature_names_out()[:20])

# Modelling
from sklearn.linear_model import LogisticRegression

model = LogisticRegression(
    max_iter=1000,
    class_weight=None,
    random_state=42
)

model.fit(X_train, y_train)
y_pred = model.predict(X_test)

print("Model training complete.")

# Intrinsic evaluation
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
    roc_auc_score,
    ConfusionMatrixDisplay
)
import matplotlib.pyplot as plt

y_prob = model.predict_proba(X_test)[:, 1]

print(f"Accuracy:  {accuracy_score(y_test, y_pred):.3f}")
print(f"Precision: {precision_score(y_test, y_pred):.3f}")
print(f"Recall:    {recall_score(y_test, y_pred):.3f}")
print(f"F1-score:  {f1_score(y_test, y_pred):.3f}")
print(f"ROC-AUC:   {roc_auc_score(y_test, y_prob):.3f}")

print("\nDetailed classification report:")
print(classification_report(
    y_test,
    y_pred,
    target_names=["ham (not spam)", "spam"],
    zero_division=0
))

ConfusionMatrixDisplay.from_predictions(
    y_test,
    y_pred,
    display_labels=["ham", "spam"],
    values_format="d"
)
plt.title("SMS Spam Detection — Confusion Matrix")
plt.show()

